function chooseImposters(){let pool=game.players.map((_,i)=>i);const fresh=pool.filter(i=>!game.recentImposters.includes(i));if(fresh.length>=imposterCount)pool=fresh;return shuffle(pool).slice(0,imposterCount)}
function startRound(){game.round++;const candidates=secretBank.filter(([s])=>!game.recentSecrets.includes(s));const [secret]=candidates[Math.floor(Math.random()*candidates.length)];game.recentSecrets=[...game.recentSecrets,secret].slice(-12);const imposters=chooseImposters();game.recentImposters=imposters;game.order=shuffle(game.players.map((_,i)=>i));game.secret=secret;game.hint=indirectHints[secret];game.imposters=imposters;game.position=0;els.roundNumber.textContent=game.round;show('handoffScreen');showHandoff();if(game.musicOn)startMusic()}
