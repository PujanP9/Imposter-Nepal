const els = Object.fromEntries(['setupScreen','handoffScreen','roleScreen','endScreen','countOutput','namesArea','imposterOptions','formError','currentPlayerName','roundNumber','progressFill','progressText','roleCard','roleIcon','roleTitle','roleLabel','roleValue','roleInstruction','nextBtn','musicBtn'].map(id=>[id,document.getElementById(id)]));
