function startMusic(){if(!game.audio){const C=window.AudioContext||window.webkitAudioContext;game.audio=new C()}const c=game.audio;if(c.state==='suspended')c.resume();if(game.musicTimer)return;const notes=[261.63,329.63,392,329.63,293.66,369.99,440,369.99];let x=0;game.musicTimer=setInterval(()=>{const o=c.createOscillator(),g=c.createGain();o.type='triangle';o.frequency.value=notes[x++%notes.length];g.gain.setValueAtTime(.0001,c.currentTime);g.gain.exponentialRampToValueAtTime(.028,c.currentTime+.025);g.gain.exponentialRampToValueAtTime(.0001,c.currentTime+.32);o.connect(g).connect(c.destination);o.start();o.stop(c.currentTime+.34)},390)}
